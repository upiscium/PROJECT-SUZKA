"""Lab-only BARE CHAT adapter of a model provider (smoke control; observation only).

Question under test: when the 12B model misreads a follow-up ('rephrase my last answer'), is it the
model (or its 4-bit quantisation), or SUZKA's large structured prompt (values, goals, commitments,
emotion, working-memory evidence ...) that steers it?  The decisive control is a plain chat:

    [system: BARE_SYSTEM_TEXT, (user, assistant) * N oldest -> newest, current user message]

``BareChatAdapter`` rewrites the model INPUT of ``generate_chat`` only.  The current user message is
the text after the builder's ``User message:`` marker; the history is the adapter's OWN list of
(current user message, model output) pairs of its earlier calls, in order.  Nothing of SUZKA's prompt
(header, runtime data, trace block, evidence) is sent.  The SUZKA runtime around it runs normally
(memory writes, ...); only what the model sees is bare.  Same inner provider, same generation settings
(they live in the inner provider), no retry, no normalisation.

OPT-IN (``serve --bare-chat``, set by the smoke only when asked).  On any doubt (no private path, no
chat template, the marker is not present exactly once, an empty message, a ``generate(prompt)`` call)
the call is passed through UNCHANGED and reported as ``adapter_skipped: <label>``; such a call adds
nothing to the history.  The history lives in this object: one provider object per serve process and
one process per subject, so it starts empty for every subject.

LAB-ONLY use of the PRIVATE names of ``TransformersProvider`` (``_uses_chat_template``,
``_chat_inputs``, ``_generate_from``), exactly as ``chat_role_adapter`` does.  Nothing under
``suzka/`` is touched.  Composition: recorder -> adapter -> model; the recorder keeps the original
two-message form and, through ``take_record_extra``, the report under the key ``bare_chat``.  Raw
text (``messages_sent``) goes only to the private 0600 file.
"""

from __future__ import annotations

from collections.abc import Callable
import json
import threading
from typing import Any

from experiments.r20.chat_role_adapter import (
    NO_CHAT_TEMPLATE, NO_PRIVATE_PATH, NOT_A_CHAT_CALL, _has_private_path, build_messages,
)
from suzka.attention.policy import ATTENTION_PROMPT_SECTION_HEADERS
from suzka.persona.prompt_builder import CURRENT_MESSAGE_HEADING, RUNTIME_DATA_HEADING

BARE_SYSTEM_TEXT = "あなたは親切なAIアシスタントです。日本語で簡潔に答えてください。"
RECORD_KEY = "bare_chat"
_MARK = f"\n\n{CURRENT_MESSAGE_HEADING}\n"

NO_USER_MESSAGE = "no_user_message"

# --- restore sections (lab isolation experiment): sections of the REAL prompt of the call, sent verbatim ---
RESTORE_NAMES = ("header", "context", "values", "wm_evidence", "motivations_goals", "emotion")  # prompt order
RESTORE_ALIAS_ALL = "all"
PLACEMENTS = ("system", "user", "first-user", "split-safe")
# Placements that put the restored data block into the FIRST user turn of the conversation (not the final one).
FIRST_USER_PLACEMENTS = ("first-user", "split-safe")
# #414 ("Must not: put any user- or model-originated text, current or stored, in the system role"): under
# ``split-safe`` only sections whose content is generated by code (the real system text, the emotion numbers, the
# context ids) may go to the SYSTEM message.  Values, working-memory evidence, motivations / goals can carry
# user- or model-originated text (stored evidence, Attention, Value names, Goal text), so they go to the first
# user turn as labelled quoted data.
SYSTEM_SAFE_SECTIONS = frozenset({"header", "emotion", "context"})
_HEADINGS = {kind.name: heading.rstrip("\n") for kind, heading in ATTENTION_PROMPT_SECTION_HEADERS}
_WM_HEADING = _HEADINGS["WORKING_MEMORY"]  # "WorkingMemory evidence:"
_MOTIVATIONS_HEADING = _HEADINGS["MOTIVATION"]  # "Current Motivations:"
_CONTEXT_HEADING = "Current Context:"
_VALUES_HEADING = "Active Values:"
_EMOTION_HEADING = "Emotion:"
_EMOTION_LINES = ("- valence:", "- arousal:", "- optimal_loss:")
_KNOWN_HEADINGS = frozenset(
    {_CONTEXT_HEADING, _VALUES_HEADING, _EMOTION_HEADING, _WM_HEADING, *_HEADINGS.values()}
)


def parse_restore_list(text: str) -> tuple[str, ...]:
    """A comma list of section names (or ``all``) -> the names in prompt order, without duplicates.

    Raises ``ValueError`` (the smoke turns it into a refusal) for an empty list or an unknown name.
    """

    names = [part.strip() for part in text.split(",")]
    if not text.strip() or any(not name for name in names):
        raise ValueError("empty restore list")
    chosen: set[str] = set()
    for name in names:
        if name == RESTORE_ALIAS_ALL:
            chosen.update(RESTORE_NAMES)
        elif name in RESTORE_NAMES:
            chosen.add(name)
        else:
            raise ValueError(f"unknown restore section: {name}")
    return tuple(name for name in RESTORE_NAMES if name in chosen)


def _block(lines: list[str], heading: str, *, stop_at_headings: bool = True) -> str | None:
    """The heading line and the lines after it up to a blank line (or another known heading), verbatim.

    ``None`` unless the heading occurs as a whole line EXACTLY once (an ambiguous or absent section is
    never guessed).  The builder separates its sections by blank lines and every stored row is a single
    line, so a blank line ends a section.
    """

    starts = [index for index, line in enumerate(lines) if line == heading]
    if len(starts) != 1:
        return None
    end = starts[0] + 1
    while end < len(lines) and lines[end] != "" and not (stop_at_headings and lines[end] in _KNOWN_HEADINGS):
        end += 1
    return "\n".join(lines[starts[0]:end])


def _emotion_block(lines: list[str]) -> str | None:
    starts = [index for index, line in enumerate(lines) if line == _EMOTION_HEADING]
    if len(starts) != 1:
        return None
    body = lines[starts[0] + 1:starts[0] + 4]
    if len(body) != 3 or not all(line.startswith(prefix) for line, prefix in zip(body, _EMOTION_LINES)):
        return None
    return "\n".join(lines[starts[0]:starts[0] + 4])


def parse_sections(system_text: str, user_text: str) -> tuple[dict[str, str], list[str]]:
    """Locate the restorable sections of ONE real call.  Returns (found name -> verbatim text, missing names).

    ``header`` is the whole real system text.  Everything else comes from the runtime data of the user text
    (the part before the builder's ``User message:`` marker, which must occur exactly once): Current Context,
    Active Values, the WorkingMemory evidence block of the Attention payload (its heading line and rows, not
    its fixed authority sentence), Current Motivations + Adopted Goals + Active Commitments (one block) and
    the three Emotion lines.  A section that is absent or ambiguous is reported as missing, never guessed.
    """

    found: dict[str, str] = {}
    if system_text.strip():
        found["header"] = system_text
    if user_text.count(_MARK) == 1:
        lines = user_text.partition(_MARK)[0].split("\n")
        if lines and lines[0] == RUNTIME_DATA_HEADING:
            for name, text in (
                ("context", _block(lines, _CONTEXT_HEADING)),
                ("values", _block(lines, _VALUES_HEADING)),
                ("wm_evidence", _block(lines, _WM_HEADING)),
                ("motivations_goals", _block(lines, _MOTIVATIONS_HEADING, stop_at_headings=False)),
                ("emotion", _emotion_block(lines)),
            ):
                if text is not None:
                    found[name] = text
    return found, [name for name in RESTORE_NAMES if name not in found]


def compose_restored(
    restore: tuple[str, ...], found: dict[str, str], placement: str, message: str,
) -> tuple[str, str, list[str]]:
    """(system text, final user text, restored names) for the bare chat plus the restored sections.

    ``system``: the sections follow ``BARE_SYSTEM_TEXT`` as one block.  ``user``: they are prepended inside
    the final user message in the builder's own shape (the header first, then the runtime-data heading, the
    other sections, a blank line, ``User message:`` and the message).  The history never holds them.
    """

    names = [name for name in restore if name in found]
    if not names:
        return BARE_SYSTEM_TEXT, message, []
    if placement == "system":
        return BARE_SYSTEM_TEXT + "\n\n" + "\n\n".join(found[name] for name in names), message, names
    head = [found["header"]] if "header" in names else []
    data = [found[name] for name in names if name != "header"]
    parts = [*head, *([RUNTIME_DATA_HEADING + "\n" + "\n\n".join(data)] if data else [])]
    return BARE_SYSTEM_TEXT, "\n\n".join(parts) + f"{_MARK}{message}", names


def compose_first_user(
    restore: tuple[str, ...], found: dict[str, str], placement: str,
) -> tuple[str, str, list[str], int, int]:
    """(system text, first-user data block, restored names, chars in system, chars in first user).

    ``first-user``: every restored section is in the block (the header first, then the real runtime-data
    heading and the other sections, verbatim).  ``split-safe``: the ``SYSTEM_SAFE_SECTIONS`` follow
    ``BARE_SYSTEM_TEXT`` and the rest is the block.  The block is attached to the first user turn by the
    caller on every call; it is never stored in the history.  The block is ``""`` when it holds nothing.
    """

    names = [name for name in restore if name in found]
    to_system = [name for name in names if name in SYSTEM_SAFE_SECTIONS] if placement == "split-safe" else []
    to_user = [name for name in names if name not in to_system]
    system = BARE_SYSTEM_TEXT + "".join("\n\n" + found[name] for name in to_system)
    head = [found["header"]] if "header" in to_user else []
    data = [found[name] for name in to_user if name != "header"]
    parts = [*head, *([RUNTIME_DATA_HEADING + "\n" + "\n\n".join(data)] if data else [])]
    return (
        system, "\n\n".join(parts), names,
        sum(len(found[name]) for name in to_system), sum(len(found[name]) for name in to_user),
    )


def apply_state_cap(
    restore: tuple[str, ...], found: dict[str, str], max_bytes: int | None,
) -> tuple[tuple[str, ...], list[str], int, int]:
    """(kept names, dropped names, UTF-8 bytes before, bytes after) of the restored state block.

    Whole sections are dropped from the END of the prompt order until the block fits ``max_bytes``
    (``None``: nothing is dropped; a section is never cut in the middle).  The bytes are those of the
    restored section texts themselves, summed over every destination.
    """

    names = [name for name in restore if name in found]
    sizes = {name: len(found[name].encode("utf-8")) for name in names}
    before = sum(sizes.values())
    kept = list(names)
    if max_bytes is not None:
        while kept and sum(sizes[name] for name in kept) > max_bytes:
            kept.pop()
    dropped = [name for name in names if name not in kept]
    return tuple(kept), dropped, before, sum(sizes[name] for name in kept)


# --- per-item evidence limits (lab; applied to the evidence rows of ``wm_evidence`` BEFORE the whole-section byte cap) ---
ELLIPSIS = "…"  # the fixed marker; it is counted in the item's character limit
EVIDENCE_TOP_K_RANGE = (1, 50)
EVIDENCE_ITEM_CHARS_RANGE = (20, 2000)
# The ONLY evidence-bearing restore section of the real (Attention) prompt.  ``Stored episodic evidence:`` /
# ``Stored semantic evidence:`` are separate sections only in the legacy builder path WITHOUT an Attention payload;
# they are not restore sections of this adapter, so they are not touched.
EVIDENCE_LIMIT_SECTIONS = ("wm_evidence",)
_WM_ROW_KEYS = {"source_kind", "text"}


def _wm_row_line(row: dict[str, Any]) -> str:
    """One row exactly as the real renderer writes it (``suzka.attention.common.canonical_json``): ASCII JSON,
    sorted keys, compact separators."""

    return json.dumps(row, ensure_ascii=True, allow_nan=False, sort_keys=True, separators=(",", ":"))


def _parse_wm_rows(block: str) -> tuple[list[dict[str, Any]], str | None]:
    """(the rows of a ``wm_evidence`` block in the builder's order, ``None``) or (``[]``, the skip reason).

    Strict: the first line is the heading, every other line must be ONE JSON object with exactly the keys
    ``source_kind`` and ``text`` (both strings) that re-serialises to the SAME line.  Anything else is a doubt.
    """

    lines = block.split("\n")
    if lines[0] != _WM_HEADING:
        return [], "wm_evidence_heading"
    rows: list[dict[str, Any]] = []
    for line in lines[1:]:
        try:
            row = json.loads(line)
        except ValueError:
            return [], "wm_evidence_row_not_json"
        if (
            not isinstance(row, dict) or set(row) != _WM_ROW_KEYS
            or not all(isinstance(value, str) for value in row.values())
        ):
            return [], "wm_evidence_row_shape"
        try:
            canonical = _wm_row_line(row) == line
        except ValueError:
            canonical = False
        if not canonical:
            return [], "wm_evidence_row_not_canonical"
        rows.append(row)
    return rows, None


def apply_evidence_limit(
    found: dict[str, str], restore: tuple[str, ...], top_k: int | None, item_max_chars: int | None,
) -> tuple[dict[str, str], dict[str, Any]]:
    """(the sections with the evidence limited, numbers); never mutates ``found``.

    Only ``wm_evidence`` (when restored and found) is touched: keep the FIRST ``top_k`` rows as rendered (no
    re-ranking), and cut the ``text`` value of each kept row to at most ``item_max_chars`` characters (code
    points; the marker ``ELLIPSIS`` is counted in them).  A cut row is re-serialised in the renderer's own
    form, so it is always one valid JSON line (no JSON escape is ever split).  The limit is on the decoded
    ``text``, NOT on the escaped line.  On any parse doubt the section stays unchanged and the numbers carry
    ``evidence_limit_skipped``.  Numbers: items / chars before and after, sections affected.
    """

    info: dict[str, Any] = {
        "evidence_items_before": 0, "evidence_items_after": 0, "evidence_chars_before": 0,
        "evidence_chars_after": 0, "evidence_sections_affected": 0, "evidence_limit_skipped": [],
    }
    if (top_k is None and item_max_chars is None) or "wm_evidence" not in restore or "wm_evidence" not in found:
        return found, info
    block = found["wm_evidence"]
    rows, reason = _parse_wm_rows(block)
    info["evidence_chars_before"] = info["evidence_chars_after"] = len(block)
    if reason is not None:
        info["evidence_limit_skipped"].append(f"evidence_limit_skipped:{reason}")
        return found, info
    info["evidence_items_before"] = info["evidence_items_after"] = len(rows)
    kept = rows if top_k is None else rows[:top_k]
    if item_max_chars is not None:
        kept = [
            row if len(row["text"]) <= item_max_chars
            else {**row, "text": row["text"][:item_max_chars - 1] + ELLIPSIS}
            for row in kept
        ]
    text = "\n".join([_WM_HEADING, *(_wm_row_line(row) for row in kept)])
    info.update(
        evidence_items_after=len(kept), evidence_chars_after=len(text),
        evidence_sections_affected=int(text != block),
    )
    return {**found, "wm_evidence": text}, info


def _token_count(inputs: Any) -> int | None:
    """Number of input tokens of the final chat-template input (a number; ``None`` when it cannot be read)."""

    try:
        return int(inputs["input_ids"].shape[-1])
    except Exception:  # noqa: BLE001 - a fixture or an unexpected shape is a recorded gap, never a crash
        return None


def cuda_reset_peak() -> None:  # pragma: no cover - needs a GPU
    try:
        import torch

        if torch.cuda.is_available():
            torch.cuda.reset_peak_memory_stats()
    except Exception:  # noqa: BLE001
        return


def cuda_peak_stats() -> tuple[int, int] | None:  # pragma: no cover - needs a GPU
    """(peak allocated bytes since the last reset, reserved bytes) of this process, or ``None``."""

    try:
        import torch

        if not torch.cuda.is_available():
            return None
        return int(torch.cuda.max_memory_allocated()), int(torch.cuda.memory_reserved())
    except Exception:  # noqa: BLE001
        return None


def extract_user_message(user_text: str) -> str | None:
    """The current user message: the text after the builder's marker; ``None`` unless the marker occurs exactly once.

    The builder renders ``<runtime data>\\n\\nUser message:\\n<user input>``.  A second marker (a message or
    a stored line imitating it) makes the split ambiguous, so it is refused rather than guessed.
    """

    if user_text.count(_MARK) != 1:
        return None
    message = user_text.partition(_MARK)[2]
    return message if message.strip() else None


class BareChatAdapter:
    """Delegates everything to ``inner``; ``generate_chat`` sends a bare chat when it can.

    ``generate_chat`` exists on the wrapper only when the inner provider has it (the app probes it).
    ``take_record_extra`` hands the report of the LAST call in this thread to the recorder.
    """

    record_extra_key = RECORD_KEY

    def __init__(
        self, inner: Any, restore: tuple[str, ...] = (), placement: str = "system", *,
        history_window: int | None = None, state_block_max_bytes: int | None = None,
        evidence_top_k: int | None = None, evidence_item_max_chars: int | None = None,
        reset_peak: Callable[[], None] = cuda_reset_peak,
        read_peak: Callable[[], tuple[int, int] | None] = cuda_peak_stats,
    ) -> None:
        if placement not in PLACEMENTS or any(name not in RESTORE_NAMES for name in restore):
            raise ValueError("invalid restore request")
        for cap in (history_window, state_block_max_bytes):
            if cap is not None and (isinstance(cap, bool) or not isinstance(cap, int) or cap < 0):
                raise ValueError("invalid input cap")
        for value, (low, high) in ((evidence_top_k, EVIDENCE_TOP_K_RANGE), (evidence_item_max_chars, EVIDENCE_ITEM_CHARS_RANGE)):
            if value is not None and (isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high):
                raise ValueError("invalid evidence limit")
        if (evidence_top_k is not None or evidence_item_max_chars is not None) and not restore:
            raise ValueError("evidence limits need restored sections")
        self._evidence_top_k = evidence_top_k
        self._evidence_chars = evidence_item_max_chars
        self._history_window = history_window
        self._state_cap = state_block_max_bytes
        self._reset_peak = reset_peak
        self._read_peak = read_peak
        self._restore = tuple(restore)
        self._placement = placement
        self._inner = inner
        self._local = threading.local()
        self._history: list[tuple[str, str]] = []
        self._lock = threading.Lock()

    def __getattr__(self, name: str) -> Any:  # only called for names not found on the wrapper
        if name in {"_inner", "_local", "_history", "_lock", "_restore", "_placement", "_history_window", "_state_cap", "_evidence_top_k", "_evidence_chars", "_reset_peak", "_read_peak"}:
            raise AttributeError(name)
        target = getattr(self._inner, name)
        return self._generate_chat if name == "generate_chat" else target

    def take_record_extra(self) -> dict[str, Any] | None:
        report = getattr(self._local, "report", None)
        self._local.report = None
        return report

    def _report(self, chars: int, reason: str | None) -> dict[str, Any]:
        report: dict[str, Any] = {
            "kind": "observed", "applied": False, "adapter_skipped": reason, "messages_sent_count": 0,
            "user_chars_before": chars, "user_chars_after": chars, "history_pairs": 0,
        }
        if self._restore:  # these keys exist only when restores were asked for (flag off: the report is unchanged)
            report.update(
                restore_requested=list(self._restore), restore_placement=self._placement,
                restored_sections=[], restored_count=0, restored_chars=0, section_missing=[],
                section_missing_count=0,
            )
            if self._placement in FIRST_USER_PLACEMENTS:  # numbers per destination, only for these placements
                report.update(restored_chars_system=0, restored_chars_first_user=0)
        if self._history_window is not None:
            report["history_window_requested"] = self._history_window
        if self._state_cap is not None:
            report["state_block_max_bytes_requested"] = self._state_cap
        if self._evidence_top_k is not None:
            report["evidence_top_k_requested"] = self._evidence_top_k
        if self._evidence_chars is not None:
            report["evidence_item_max_chars_requested"] = self._evidence_chars
        return report

    def generate(self, prompt: str) -> str:
        self._local.report = self._report(len(prompt), NOT_A_CHAT_CALL)
        return self._inner.generate(prompt)

    def _generate_chat(self, system_text: str, user_text: str) -> str:
        report = self._report(len(user_text), None)
        self._local.report = report
        inner = self._inner
        reason: str | None = None
        message: str | None = None
        if not _has_private_path(inner):
            reason = NO_PRIVATE_PATH
        elif not inner._uses_chat_template():
            reason = NO_CHAT_TEMPLATE
        else:
            message = extract_user_message(user_text)
            if message is None:
                reason = NO_USER_MESSAGE
        if reason is not None or message is None:
            report["adapter_skipped"] = reason
            return inner.generate_chat(system_text, user_text)  # unchanged, exactly as without the adapter
        with self._lock:
            history = list(self._history)
        system, final = BARE_SYSTEM_TEXT, message
        pairs = history
        if self._history_window is not None:  # the most recent N exchanges; the stored history stays whole
            pairs = history[-self._history_window:] if self._history_window else []
            report.update(history_pairs_sent=len(pairs), exchanges_dropped=len(history) - len(pairs))
        if self._restore:
            found, missing = parse_sections(system_text, user_text)
            wanted_missing = [name for name in self._restore if name in missing]
            # order: evidence limits first (rows of wm_evidence), then the whole-section byte cap (sections)
            found, evidence = apply_evidence_limit(found, self._restore, self._evidence_top_k, self._evidence_chars)
            if self._evidence_top_k is not None or self._evidence_chars is not None:
                report.update(evidence)
            restore, dropped, bytes_before, bytes_after = apply_state_cap(self._restore, found, self._state_cap)
            if self._state_cap is not None:
                report.update(
                    state_bytes_before=bytes_before, state_bytes_effective=bytes_after,
                    sections_dropped=len(dropped), sections_dropped_names=dropped,
                )
            if self._placement in FIRST_USER_PLACEMENTS:
                system, block, restored, chars_system, chars_first = compose_first_user(
                    restore, found, self._placement,
                )
                if block and pairs:  # re-attached on EVERY call to the first user turn; the stored pair stays raw
                    pairs = [(block + _MARK + pairs[0][0], pairs[0][1]), *pairs[1:]]
                elif block:
                    final = block + _MARK + message
                report.update(restored_chars_system=chars_system, restored_chars_first_user=chars_first)
            else:
                system, final, restored = compose_restored(restore, found, self._placement, message)
            report.update(
                restored_sections=restored, restored_count=len(restored),
                restored_chars=sum(len(found[name]) for name in restored),
                section_missing=[f"section_missing:{name}" for name in wanted_missing],
                section_missing_count=len(wanted_missing),
            )
        messages = build_messages(system, pairs, final)
        if self._restore:
            report["input_chars"] = sum(len(part["text"]) for item in messages for part in item["content"])
        report.update(
            applied=True, messages_sent_count=len(messages), user_chars_after=len(final),
            history_pairs=len(history),
            messages_sent=messages,  # RAW text: private file only
        )
        inputs = inner._chat_inputs(messages)
        report["input_tokens"] = _token_count(inputs)  # numbers only
        try:
            self._reset_peak()
        except Exception:  # noqa: BLE001 - a failed hook is a gap, never a crash
            pass
        output = inner._generate_from(inputs)
        try:
            peak = self._read_peak()
        except Exception:  # noqa: BLE001
            peak = None
        if peak is not None:
            report.update(peak_allocated_bytes=int(peak[0]), reserved_bytes=int(peak[1]))
        with self._lock:
            self._history.append((message, str(output)))
        return output


def wrap_loader(
    loader: Callable[..., Any], restore: tuple[str, ...] = (), placement: str = "system", *,
    history_window: int | None = None, state_block_max_bytes: int | None = None,
    evidence_top_k: int | None = None, evidence_item_max_chars: int | None = None,
) -> Callable[..., Any]:
    """A drop-in for ``load_model_provider``: every provider it builds is wrapped (one history per provider)."""

    def load(*arguments: Any, **keywords: Any) -> BareChatAdapter:
        return BareChatAdapter(
            loader(*arguments, **keywords), restore, placement,
            history_window=history_window, state_block_max_bytes=state_block_max_bytes,
            evidence_top_k=evidence_top_k, evidence_item_max_chars=evidence_item_max_chars,
        )

    return load


def numbers(row: dict[str, Any]) -> dict[str, Any] | None:
    """The adapter's report of a recorded call WITHOUT the messages (numbers and labels only)."""

    report = row.get(RECORD_KEY)
    if not isinstance(report, dict):
        return None
    return {key: value for key, value in report.items() if key != "messages_sent"}


